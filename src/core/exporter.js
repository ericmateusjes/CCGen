/* CCGen núcleo: formatação, tabelas em texto, bloco .inp do Abaqus e JSON de configuração. */
(function (G) {
  'use strict';
  const E = {};
  E.fmt = function (x, o) {
    o = o || {};
    const dg = o.digits == null ? 6 : o.digits, nt = o.notation || 'sci';
    if (!isFinite(x)) return String(x);
    if (nt === 'fixed') return x.toFixed(dg);
    if (nt === 'auto') { const a = Math.abs(x); return (a !== 0 && (a < 1e-3 || a >= 1e5)) ? x.toExponential(dg - 1) : String(+x.toPrecision(dg)); }
    return x.toExponential(dg - 1);                     // científica
  };
  E.fmtD = function (x, o) { const t = E.fmt(x, o); return o && o.dec === 'comma' ? t.replace('.', ',') : t; };
  const SEP = { comma: ', ', tab: '\t', space: ' ', semicolon: '; ' };
  E.tableText = function (rows, o) {
    o = o || {}; const sep = SEP[o.sep || 'comma'];
    return rows.map((r) => r.map((v) => E.fmtD(v, o)).join(sep)).join('\n');
  };
  /** Sistemas de unidades de saída (o cálculo é sempre em N, mm, MPa). lf: mm → comprimento; ff: N → força. */
  E.UNITS = {
    Nmm: { label: 'N, mm, MPa (default)', F: 'N', L: 'mm', S: 'MPa', lf: 1, ff: 1 },
    Nm: { label: 'N, m, Pa', F: 'N', L: 'm', S: 'Pa', lf: 1e-3, ff: 1 },
    kNm: { label: 'kN, m, kPa', F: 'kN', L: 'm', S: 'kPa', lf: 1e-3, ff: 1e-3 },
    kNmm: { label: 'kN, mm, kN/mm²', F: 'kN', L: 'mm', S: 'kN/mm²', lf: 1, ff: 1e-3 },
    Ncm: { label: 'N, cm, N/cm²', F: 'N', L: 'cm', S: 'N/cm²', lf: 0.1, ff: 1 }
  };
  /** Tabelas e E0 no sistema de unidades escolhido. */
  E.scaled = function (res, uk) {
    const u = E.UNITS[uk || 'Nmm'] || E.UNITS.Nmm, sf = u.ff / (u.lf * u.lf), t = res.tables, T = res.tens;
    const sc = (rows) => rows.map((r) => [r[0] * sf, r[1]]);
    return { unit: u, sf, E0: res.props.E0 * sf,
      compHardening: sc(t.compHardening), compDamage: t.compDamage.map((r) => r.slice()), tensStiffening: sc(t.tensStiffening), tensDamage: t.tensDamage.map((r) => r.slice()),
      tensStiffeningW: T.w.map((w, i) => [T.sigma[i] * sf, w * u.lf]), tensDamageW: T.w.map((w, i) => [T.d[i], w * u.lf]) };
  };
  /** Parâmetros do bloco CDP. */
  E.CDP_PRESETS = {
    abaqus: { label: 'Abaqus defaults (ψ is a typical value; calibrate)', psi: 36, ecc: 0.1, fb0fc0: 1.16, K: 2 / 3, visc: 0 },
    alfarah: { label: 'Alfarah et al. (2017)', psi: 13, ecc: 0.1, fb0fc0: 1.16, K: 0.7, visc: 0 }
  };
  /** Bloco *MATERIAL do Abaqus. o: {name, nu, density, cdp, tensionType: strain|displacement, ...} */
  E.inp = function (res, o) {
    if (!res || !res.ok || !res.tables) throw new G.util.CCGenError('There are no valid results to export.', 'EXPORT');
    o = o || {};
    const cdp = Object.assign({}, E.CDP_PRESETS.abaqus, o.cdp || {});
    const f = { notation: o.notation || 'sci', digits: o.digits || 6 };
    const sc = E.scaled(res, o.units), tb = sc, disp = o.tensionType === 'displacement';
    const L = [];
    L.push('** Generated by CCGen v' + G.util.VERSION + ' - fck = ' + res.cfg.fck + ' MPa, l_eq = ' + res.cfg.leq + ' mm (units: ' + sc.unit.F + ', ' + sc.unit.L + ', ' + sc.unit.S + ')');
    L.push('** Compression: ' + G.compression.MODELS[res.cfg.compModel] + ' | damage: ' + G.damage.METHODS[res.cfg.compDamage]);
    L.push('** Tension: ' + G.tension.MODELS[res.cfg.tensModel] + ' | damage: ' + G.damage.METHODS[res.cfg.tensDamage]);
    L.push('*MATERIAL, NAME=' + (o.name || 'CONCRETE'));
    if (o.density) { L.push('*DENSITY'); L.push(E.fmt(o.density, f) + ','); }
    L.push('*ELASTIC'); L.push(E.fmt(sc.E0, f) + ', ' + (o.nu == null ? 0.2 : o.nu));
    L.push('*CONCRETE DAMAGED PLASTICITY');
    L.push([cdp.psi, cdp.ecc, cdp.fb0fc0, +cdp.K.toFixed(6), cdp.visc].join(', '));
    L.push('*CONCRETE COMPRESSION HARDENING'); L.push(E.tableText(tb.compHardening, Object.assign({ sep: 'comma' }, f)));
    L.push('*CONCRETE COMPRESSION DAMAGE'); L.push(E.tableText(tb.compDamage, Object.assign({ sep: 'comma' }, f)));
    if (disp) {
      L.push('*CONCRETE TENSION STIFFENING, TYPE=DISPLACEMENT'); L.push(E.tableText(sc.tensStiffeningW, f));
      L.push('*CONCRETE TENSION DAMAGE, TYPE=DISPLACEMENT'); L.push(E.tableText(sc.tensDamageW, f));
    } else {
      L.push('*CONCRETE TENSION STIFFENING'); L.push(E.tableText(tb.tensStiffening, f));
      L.push('*CONCRETE TENSION DAMAGE'); L.push(E.tableText(tb.tensDamage, f));
    }
    return L.join('\n') + '\n';
  };
  /** As quatro tabelas lado a lado em CSV (a primeira linha "sep=;" fixa o separador no Excel). */
  E.csv = function (res, o) {
    if (!res || !res.tables) throw new G.util.CCGenError('There are no valid results to export.', 'EXPORT');
    o = o || {}; const sc = E.scaled(res, o.units), S = sc.unit.S, disp = o.tensionData === 'displacement', f = { notation: o.notation || 'auto', digits: o.digits || 6, dec: o.dec };
    const xt = disp ? 'w (' + sc.unit.L + ')' : 'eps_t^ck (-)';
    const blocks = [['Compression hardening', ['sigma_c (' + S + ')', 'eps_c^ch (-)'], sc.compHardening], ['Compression damage', ['d_c (-)', 'eps_c^ch (-)'], sc.compDamage],
      ['Tension stiffening', ['sigma_t (' + S + ')', xt], disp ? sc.tensStiffeningW : sc.tensStiffening], ['Tension damage', ['d_t (-)', xt], disp ? sc.tensDamageW : sc.tensDamage]];
    const n = Math.max.apply(null, blocks.map((b) => b[2].length)), L = ['sep=;'], line = (fn) => blocks.map(fn).join(';;');
    L.push(line((b) => b[0] + ';')); L.push(line((b) => b[1].join(';')));
    for (let i = 0; i < n; i++) L.push(line((b) => (b[2][i] ? b[2][i].map((v) => E.fmtD(v, f)).join(';') : ';')));
    return L.join('\r\n') + '\r\n';
  };
  /** JSON da configuração (tudo, exceto os resultados). */
  E.configJSON = function (res) {
    const c = G.util.clone(res.cfg);
    return JSON.stringify({ ccgen: G.util.VERSION, created: new Date().toISOString(), config: c, origins: res.origins,
      properties: res.props, warnings: res.warnings.map((w) => w.id + ': ' + w.msg) }, null, 2);
  };
  E.parseConfig = function (text) {
    let j; try { j = JSON.parse(text); } catch (e) { throw new G.util.CCGenError('The file is not valid JSON.', 'CONFIG'); }
    if (!j || typeof j !== 'object' || !j.config || typeof j.config.fck !== 'number') throw new G.util.CCGenError('Not a CCGen configuration file.', 'CONFIG');
    return j.config;
  };
  G.exporter = E;
})(globalThis.CCGen = globalThis.CCGen || {});
